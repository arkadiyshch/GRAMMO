def process_successful_payment(yookassa_payment_id):

    with pool.connection() as conn:

        try:

            with conn.cursor() as cursor:

                # ----------------------------------------------------
                # Блокируем конкретный платёж.
                #
                # Это PostgreSQL-аналог защиты от двух
                # одновременно пришедших webhook.
                # ----------------------------------------------------

                cursor.execute("""
                    SELECT
                        id,
                        user_id,
                        subscription_id,
                        status
                    FROM payments
                    WHERE yookassa_payment_id = %s
                    FOR UPDATE
                """, (yookassa_payment_id,))

                payment = cursor.fetchone()

                if payment is None:
                    raise ValueError(
                        f"Payment not found: {yookassa_payment_id}"
                    )

                payment_id = payment[0]
                user_id = payment[1]
                subscription_id = payment[2]
                status = payment[3]

                # ----------------------------------------------------
                # Уже обработан
                # ----------------------------------------------------

                if status == "succeeded":

                    conn.commit()

                    return {
                        "status": "already_processed",
                        "user_id": user_id
                    }

                # ----------------------------------------------------
                # Получаем срок подписки
                # ----------------------------------------------------

                cursor.execute("""
                    SELECT period_months
                    FROM subscriptions
                    WHERE id = %s
                """, (subscription_id,))

                subscription = cursor.fetchone()

                if subscription is None:
                    raise ValueError(
                        f"Subscription not found: {subscription_id}"
                    )

                period_months = subscription[0]

                if period_months is None:
                    raise ValueError(
                        f"Subscription has no period_months: {subscription_id}"
                    )

                started_at = datetime.now()

                expires_at = started_at + timedelta(
                    days=31 * period_months
                )

                # ----------------------------------------------------
                # Создаём подписку
                # ----------------------------------------------------

                cursor.execute("""
                    INSERT INTO user_subscriptions (
                        user_id,
                        subscription_id,
                        payment_id,
                        started_at,
                        expires_at
                    )
                    VALUES (%s, %s, %s, %s, %s)
                    ON CONFLICT (payment_id) DO NOTHING
                """, (
                    user_id,
                    subscription_id,
                    payment_id,
                    started_at,
                    expires_at
                ))

                # ----------------------------------------------------
                # Помечаем платёж как успешно обработанный
                # ----------------------------------------------------

                cursor.execute("""
                    UPDATE payments
                    SET
                        status = 'succeeded',
                        paid_at = CURRENT_TIMESTAMP
                    WHERE id = %s
                """, (payment_id,))

            conn.commit()

            return {
                "status": "activated",
                "user_id": user_id,
                "subscription_id": subscription_id,
                "payment_id": payment_id
            }

        except Exception:

            conn.rollback()
            raise



