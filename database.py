def create_tables():
    with pool.connection() as conn:
        try:
            with conn.cursor() as cursor:

                # ============================================================
                # USERS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS users (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL UNIQUE,
                        user_name TEXT,
                        email TEXT
                    );
                """)

                # ============================================================
                # LEVELS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS levels (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        code TEXT NOT NULL UNIQUE,
                        sort_order INTEGER NOT NULL
                    );
                """)

                # ============================================================
                # SUBSCRIPTIONS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS subscriptions (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        code TEXT NOT NULL UNIQUE,
                        name TEXT NOT NULL,
                        price INTEGER NOT NULL DEFAULT 0,
                        period_months INTEGER,
                        daily_limit INTEGER
                    );
                """)

                # ============================================================
                # DIFFICULTY
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS difficulty (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        description TEXT,
                        description_short TEXT
                    );
                """)

                # ============================================================
                # GRAMMAR TOPICS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS grammar_topics (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        parent_id BIGINT,
                        level_id BIGINT,

                        FOREIGN KEY (parent_id)
                            REFERENCES grammar_topics(id),

                        FOREIGN KEY (level_id)
                            REFERENCES levels(id)
                    );
                """)

                # ============================================================
                # LEXICAL TOPICS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS lexical_topics (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        name TEXT NOT NULL,
                        parent_id BIGINT,
                        level_from BIGINT NOT NULL,
                        subscription_id BIGINT NOT NULL DEFAULT 1,

                        FOREIGN KEY (parent_id)
                            REFERENCES lexical_topics(id),

                        FOREIGN KEY (level_from)
                            REFERENCES levels(id),

                        FOREIGN KEY (subscription_id)
                            REFERENCES subscriptions(id)
                    );
                """)

                # ============================================================
                # SENTENCES
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS sentences (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        sentence TEXT NOT NULL,
                        level_id BIGINT NOT NULL,
                        grammar_topic_id BIGINT,
                        lexical_topic_id BIGINT,
                        difficulty_id BIGINT,
                        type INTEGER NOT NULL DEFAULT 0,
                        tips TEXT,
                        translation TEXT,

                        FOREIGN KEY (level_id)
                            REFERENCES levels(id),

                        FOREIGN KEY (grammar_topic_id)
                            REFERENCES grammar_topics(id),

                        FOREIGN KEY (lexical_topic_id)
                            REFERENCES lexical_topics(id),

                        FOREIGN KEY (difficulty_id)
                            REFERENCES difficulty(id)
                    );
                """)

                # ============================================================
                # PAYMENTS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS payments (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        subscription_id BIGINT NOT NULL,
                        yookassa_payment_id TEXT NOT NULL UNIQUE,
                        amount INTEGER NOT NULL,
                        currency TEXT NOT NULL DEFAULT 'RUB',
                        status TEXT NOT NULL,
                        created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                        paid_at TIMESTAMP,

                        FOREIGN KEY (user_id)
                            REFERENCES users(user_id),

                        FOREIGN KEY (subscription_id)
                            REFERENCES subscriptions(id)
                    );
                """)

                # ============================================================
                # USER ANSWERS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS user_answers (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        sentence_id BIGINT NOT NULL,
                        user_answer TEXT,
                        ai_answer TEXT,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                        FOREIGN KEY (user_id)
                            REFERENCES users(user_id),

                        FOREIGN KEY (sentence_id)
                            REFERENCES sentences(id)
                    );
                """)

                # ============================================================
                # USER DIFFICULTY
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS user_difficulty (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        difficulty_id BIGINT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                        FOREIGN KEY (user_id)
                            REFERENCES users(user_id),

                        FOREIGN KEY (difficulty_id)
                            REFERENCES difficulty(id)
                    );
                """)

                # ============================================================
                # USER LEVELS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS user_levels (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        user_id BIGINT NOT NULL,
                        user_level TEXT,
                        estimated_level TEXT,
                        source TEXT NOT NULL,
                        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

                        FOREIGN KEY (user_id)
                            REFERENCES users(user_id)
                    );
                """)

                # ============================================================
                # USER SUBSCRIPTIONS
                # ============================================================

                cursor.execute("""
                    CREATE TABLE IF NOT EXISTS user_subscriptions (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                        user_id BIGINT NOT NULL,
                        subscription_id BIGINT NOT NULL,
                        payment_id BIGINT NOT NULL,

                        started_at TIMESTAMP NOT NULL,
                        expires_at TIMESTAMP NOT NULL,

                        FOREIGN KEY (user_id)
                            REFERENCES users(user_id),

                        FOREIGN KEY (subscription_id)
                            REFERENCES subscriptions(id),

                        FOREIGN KEY (payment_id)
                            REFERENCES payments(id),

                        UNIQUE(payment_id)
                    );
                """)

            conn.commit()

        except Exception:
            conn.rollback()
            raise

        finally:
            conn.close()


def add_user(telegram_id: int, username: str):
    with pool.connection() as conn:
        try:
            with conn.cursor() as cursor:

                cursor.execute("""
                    SELECT id
                    FROM users
                    WHERE user_id = %s
                """, (telegram_id,))

                user = cursor.fetchone()

                if user is not None:
                    return False

                cursor.execute("""
                    INSERT INTO users (
                        user_id,
                        user_name
                    )
                    VALUES (%s, %s)
                """, (
                    telegram_id,
                    username
                ))

            conn.commit()
            return True

        except Exception:
            conn.rollback()
            raise

     


